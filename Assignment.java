class Assignment
{

public static void main (String[] args)
{

int a;
System.out.println("Assigning:"+(a = 10));
System.out.println("Add:"+(a += 20));
System.out.println("Sub:"+(a -= 10));
System.out.println("Multiply:"+(a *= 10));
System.out.println("Divide:"+(a /= 10));
System.out.println("Modulo:"+(a %= 3));

}

}